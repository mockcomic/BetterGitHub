import { join } from 'path'
import { BrowserWindow, nativeTheme } from 'electron'
import { themeBase, themeFrame, type ThemeId } from '../shared/themes'
import { logDiagnostics } from './diagnostics'

let mainWindow: BrowserWindow | null = null

const trustedWebContents = new Set<number>()

/**
 * The theme half of the window chrome. The palette registry
 * (shared/themes.ts) carries each theme's frame colors — the content
 * background and the win32 caption strip read as the same surfaces the
 * renderer paints with --bg / --bg-header / --text, so the OS-drawn
 * chrome is never an off-theme grey box. These stay in lockstep with
 * styles.css, where they are the token values themselves.
 */
let currentTheme: ThemeId = 'system'

/** The title band's height (styles.css .titlebar); the caption buttons and
 *  the band share this single height so they end on the same line. */
const titleBarHeight = 40

function prefersDark(): boolean {
  // applyTheme sets nativeTheme.themeSource before the first window is
  // built, so this resolves the saved setting — including 'system' — correctly.
  return nativeTheme.shouldUseDarkColors
}

/** Repaint the OS-drawn chrome: the content background everywhere, and on
 *  Windows the Window Controls Overlay caption strip behind the buttons. */
function paintWindowChrome(window: BrowserWindow): void {
  if (window.isDestroyed()) return
  const colors = themeFrame(currentTheme, prefersDark())
  window.setBackgroundColor(colors.ground)
  if (process.platform === 'win32') {
    window.setTitleBarOverlay({
      color: colors.frame,
      symbolColor: colors.symbols
    })
  }
}

// With the setting on 'system', an OS scheme flip changes shouldUseDarkColors
// without any app action; the renderer follows the media query on its own, so
// this listener exists to keep the native frame in step.
nativeTheme.on('updated', () => {
  for (const window of BrowserWindow.getAllWindows()) paintWindowChrome(window)
})

/**
 * The desktop mark (resources/gitdesk-icon.svg, generated by `npm run icons`).
 * Resolved relative to out/main, which is the same depth inside the asar as in
 * a development checkout, so the path holds in both layouts. Windows reads the
 * .ico directly; elsewhere a PNG is the safer payload, and a packaged macOS
 * app gets its icon from the bundle rather than from here.
 */
export const windowIcon =
  process.platform === 'win32'
    ? join(__dirname, '../../resources/icons/gitdesk.ico')
    : join(__dirname, '../../resources/icons/png/256x256.png')

export function createMainWindow(devServerUrl: string | undefined): BrowserWindow {
  const colors = themeFrame(currentTheme, prefersDark())
  const window = new BrowserWindow({
    width: 1280,
    height: 840,
    minWidth: 960,
    minHeight: 600,
    // Matches the theme's work ground (styles.css), so the first paint and any
    // resize gutter read as the desk, not as a grey box.
    backgroundColor: colors.ground,
    // On Windows the OS title bar is hidden and the caption buttons are a
    // Window Controls Overlay painted from the palette's chrome tone; the
    // renderer shows a matching title band (styles.css .titlebar) as the
    // window's drag handle, sized to the same height (titleBarHeight) and
    // kept away from the caption safe area via env(titlebar-area-*). The
    // renderer knows the overlay is on through the preload's platform tag.
    ...(process.platform === 'win32'
      ? {
          titleBarStyle: 'hidden' as const,
          titleBarOverlay: {
            color: colors.frame,
            symbolColor: colors.symbols,
            height: titleBarHeight
          }
        }
      : {}),
    // Shown on the taskbar button (with the App User Model ID set in
    // index.ts); a packaged build falls back to the exe's icon.
    icon: windowIcon,
    // The win32 standard menu bar is hidden — its items are unreachable
    // clutter under the title band, which carries the menu labels itself
    // and pops the same native menus (src/main/menu.ts popupMenuAt); the
    // accelerators stay live with the bar hidden, and Alt still summons it.
    // Elsewhere (linux) the menu stays visible as before.
    autoHideMenuBar: process.platform === 'win32',
    webPreferences: {
      preload: join(__dirname, '../preload/index.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false,
      spellcheck: false
    }
  })

  // Captured eagerly: after 'closed' fires, `window.webContents` is already
  // destroyed and reading `.id` throws "Object has been destroyed".
  const contentsId = window.webContents.id
  trustedWebContents.add(contentsId)

  window.webContents.on(
    'did-fail-load',
    (_event, errorCode, errorDescription, validatedUrl) => {
      logDiagnostics(
        `did-fail-load: code=${errorCode} desc=${errorDescription} url=${validatedUrl}`
      )
    }
  )
  window.webContents.on(
    'render-process-gone',
    (_event, details) => {
      logDiagnostics(
        `window render-process-gone: reason=${details.reason}`
      )
    }
  )
  window.webContents.on('unresponsive', () => {
    logDiagnostics('window unresponsive')
  })
  window.webContents.on('did-finish-load', () => {
    logDiagnostics(`window did-finish-load: ${window.webContents.getURL()}`)
  })
  window.webContents.on(
    'console-message',
    (
      _event,
      level: unknown,
      message: string,
      lineNumber: number,
      sourceId: string
    ) => {
      const levelName = String(level).toLowerCase()
      if (levelName.includes('error') || levelName.includes('warn')) {
        logDiagnostics(
          `renderer console (${levelName}) ${sourceId}:${lineNumber}: ${message}`
        )
      }
    }
  )

  window.on('closed', () => {
    trustedWebContents.delete(contentsId)
    if (mainWindow === window) mainWindow = null
  })

  if (devServerUrl !== undefined) {
    void window.loadURL(devServerUrl)
  } else {
    void window.loadFile(join(__dirname, '../renderer/index.html'))
  }

  mainWindow = window
  return window
}

export function getMainWindow(): BrowserWindow | null {
  return mainWindow !== null && !mainWindow.isDestroyed() ? mainWindow : null
}

export function isTrustedSender(webContentsId: number): boolean {
  return trustedWebContents.has(webContentsId)
}

export function applyTheme(theme: ThemeId): void {
  currentTheme = theme
  // 'system' must keep nativeTheme itself on 'system' so the OS scheme
  // stays authoritative — pinning it to the resolved family would freeze
  // the media query and shouldUseDarkColors against future OS flips (the
  // 'updated' listener above relies on that). A fixed theme pins the
  // resolved family so OS-drawn surfaces (native scrollbars, form
  // controls) follow the palette instead of the OS.
  nativeTheme.themeSource =
    theme === 'system' ? 'system' : themeBase(theme, nativeTheme.shouldUseDarkColors)
  // themeSource just re-resolved shouldUseDarkColors; repaint the existing
  // window's OS chrome (background + win32 frame) to match. New windows pick
  // the same colors up in createMainWindow.
  for (const window of BrowserWindow.getAllWindows()) paintWindowChrome(window)
}
